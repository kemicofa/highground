local t = dofile("../../tools/harness.lua")("async attempts")
local ns = {}
assert(loadfile("libs/core/Async.lua"))("Test", ns)

t.test("retrying the same value invalidates old timers and duplicate completions", function()
  local op, item = ns.Async.New(), {}
  t.equal(op.state, "idle", "initial state")
  local first = op:Start(item)
  assert(op:Finish(first, "failed", "timeout"))
  local retry = op:Start(item)
  assert(not op:Finish(first, "failed"), "old timeout cannot finish retry")
  assert(not op:Finish(first, "succeeded"), "late success cannot finish retry")
  assert(op:IsCurrent(retry))
  assert(op:Finish(retry, "succeeded"))
  assert(not op:Finish(retry, "failed"), "completed attempt cannot change outcome")
  t.equal(op.state, "succeeded", "final outcome")
  t.equal(first.message, "timeout", "failure retained on its own attempt")
end)

t.test("replacement and cancellation retire callbacks without affecting another operation", function()
  local a, b = ns.Async.New(), ns.Async.New()
  local first = a:Start("first")
  local second = a:Start("second")
  local other = b:Start("other")
  t.equal(first.state, "cancelled", "replacement cancels prior attempt")
  assert(not a:Finish(other, "succeeded"), "foreign attempt rejected")
  assert(a:Cancel("closed"))
  assert(not a:IsCurrent(second) and not a:Cancel(), "cancellation is idempotent")
  assert(b:IsCurrent(other), "independent operation unaffected")
  assert(not pcall(a.Finish, a, second, "typo"), "invalid outcomes are programming errors")
  local unavailable = a:Start()
  assert(a:Finish(unavailable, "unavailable"))
  t.equal(a.state, "unavailable", "unsupported operation explicit")
end)

t.finish("Async attempts: " .. t.tests .. " scenarios")
