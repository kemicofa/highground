-- Legacy keys, profile import and export, base64, the share window.
local o = ...
local client, visible, equal = o.client, o.visible, o.equal
local old = client("cata", { kit42292 = 12, trinketDown = 3 })
equal(old.db.points.kit42292, nil, "legacy duplicate trinket key is removed")
equal(old.db.points.trinketDown, 12, "effective legacy override is preserved")
equal(old.ui.cooldown({ class = "NONE", cds = { [42292] = 150 } }), 12, "live scoring uses the canonical trinket value")
old:edit("PvP trinket on cooldown", "4")
equal(old.ui.cooldown({ class = "NONE", cds = { [42292] = 150 } }), 4, "the only trinket control directly changes scoring")
local ok = old.ui.profiles.ImportText("WB1;f=cata;p.kit42292=0;p.trinketDown=9;p.kit5277=17")
equal(ok, true, "legacy profiles still import")
equal(old.db.points.trinketDown, 0, "import preserves a zero trinket override")
equal(old.db.points.kit42292, nil, "import cannot recreate the duplicate")
equal(old.db.points.kit5277, 17, "unrelated spell overrides survive import")
old.ui.profiles.SaveProfile("Saved")
equal(old.db.profiles.Saved.points.trinketDown, 0, "saved profiles use the canonical trinket key")
equal(old.db.profiles.Saved.points.kit42292, nil, "new profiles omit the duplicate")
old.ui.profiles.ShowExport("Saved")
local P = old.ui.profiles
local encoded = P.share.box.text
assert(encoded:match("^[%w%+/=]+$"), "export is base64")
local export = P.Decode64(encoded)
assert(export and export:match("^WB1;n=Saved;"), "export carries the profile name")
assert(export:find("p.trinketDown=0", 1, true) and not export:find("kit42292", 1, true), "export contains one trinket setting")
equal(P.Decode64(P.Encode64("a")), "a", "base64 round trip, one byte")
equal(P.Decode64(P.Encode64("ab")), "ab", "base64 round trip, two bytes")
equal(P.Encode64("Man"), "TWFu", "RFC 4648 vector")
equal(P.Decode64("not base64!"), nil, "invalid base64 rejected")
local parsed = P.ParseString(encoded)
equal(parsed.name, "Saved", "name read back")
equal(parsed.points.trinketDown, 0, "values read back")
local okSave, saveMsg = P.SaveImported(P.ExportString({ points = { trinketDown = 7 }, weights = {}, specs = {}, options = {},
  flavor = "cata" }, "Friend's PvP"), "")
equal(okSave, true, "shared profile saved: " .. tostring(saveMsg))
equal(old.db.profiles["Friend's PvP"].points.trinketDown, 7, "saved under its exported name")
equal(old.db.points.trinketDown, 0, "saving does not apply it")
equal((P.SaveImported(P.Encode64("WB1;f=cata;p.trinketDown=abc"), "Bad")), false, "invalid values are not saved")
equal(old.db.profiles.Bad, nil, "nothing stored on failure")
local okApply = P.ImportText(P.ExportString({ points = { trinketDown = 5 }, weights = {}, specs = {}, options = {},
  flavor = "cata" }, "X"))
equal(okApply, true, "base64 imports apply")
equal(old.db.points.trinketDown, 5, "applied value")
P.ShowImport()
equal(P.share.mode, "import", "import window mode")
equal(P.share.actions.apply.shown, true, "Apply shown for import")
P.share.box:SetText(encoded)
equal(P.share.name:GetText(), "Saved", "pasted export fills the name")
P.share.name:SetText("Pasted")
P.share.actions.save.scripts.OnClick(P.share.actions.save)
equal(old.db.profiles.Pasted.points.trinketDown, 0, "Save as profile keeps the paste")
equal(P.share.status.text, "saved profile Pasted (load it to apply)", "status line")
P.share.box:SetText("garbage")
P.share.actions.apply.scripts.OnClick(P.share.actions.apply)
equal(P.share.status.text, "not a Highground profile", "invalid paste reported")
equal(P.share.status.wbToken, "error", "error status colour")
P.ShowExport("Saved")
equal(P.share.actions.apply.shown, false, "export has no Apply")
equal(P.DeleteProfile("Pasted"), true, "delete a profile")
equal(old.db.profiles.Pasted, nil, "deleted")
equal(P.DeleteProfile("Pasted"), false, "deleting twice is a no-op")
local customized = client("cata", { kit5277 = 0 })
equal(visible(customized:row("Evasion")), true, "existing custom spell values are visible on first open")
assert(customized:find("Button", "Hide spell overrides (1)"), "override count makes custom tuning visible")
