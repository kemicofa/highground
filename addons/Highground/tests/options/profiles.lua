-- Legacy keys, profile import and export, base64, the export and import windows.
local o = ...
local client, visible, equal = o.client, o.visible, o.equal
local old = client("cata", { kit42292 = 12, trinketDown = 3 })
local CS, P = old.ns.CharacterSettings, old.ui.profiles
local function find(name)
  for _, item in ipairs(CS.Profiles("battlegrounds")) do if item.name == name and item.kind == "import" then return item end end
end
equal(old.db.points.kit42292, nil, "legacy duplicate trinket key is removed")
equal(old.db.points.trinketDown, 12, "effective legacy override is preserved")
equal(old.ui.cooldown({ class = "NONE", cds = { [42292] = 150 } }), 12, "live scoring uses the canonical trinket value")
old:edit("PvP trinket on cooldown", "4")
equal(old.ui.cooldown({ class = "NONE", cds = { [42292] = 150 } }), 4, "the only trinket control directly changes scoring")
local ok, _, index = CS.Import("WB1;f=cata;p.kit42292=0;p.trinketDown=9;p.kit5277=17")
equal(ok, true, "legacy profiles still import")
equal(old.db.points.trinketDown, 4, "importing does not apply it")
equal(CS.Copy({ import = index }, "battlegrounds"), true, "the import copies into this character")
equal(old.db.points.trinketDown, 0, "import preserves a zero trinket override")
equal(old.db.points.kit42292, nil, "import cannot recreate the duplicate")
equal(old.db.points.kit5277, 17, "unrelated spell overrides survive import")
CS.Select("bg40")
equal(old.db.points.trinketDown, 0, "every battleground size gets the canonical trinket value")
equal(old.db.points.kit42292, nil, "and no duplicate")
CS.Select("bg10")
local code = CS.Export("battlegrounds")
assert(code:match("^[%w%+/=]+$"), "export is base64")
local export = P.Decode64(code)
assert(export and export:match("^WB2;n=Tester;"), "export carries the character name")
local parsed = CS.Parse(code)
equal(parsed.name, "Tester", "name read back")
equal(parsed.addons.battlegrounds.bg10.points.trinketDown, 0, "this character's settings use the canonical trinket key")
equal(parsed.addons.battlegrounds.bg10.points.kit42292, nil, "exports omit the duplicate")
equal(P.ShowExport("battlegrounds"):GetText(), code, "the export window shows the same code")
equal(P.Decode64(P.Encode64("a")), "a", "base64 round trip, one byte")
equal(P.Decode64(P.Encode64("ab")), "ab", "base64 round trip, two bytes")
equal(P.Encode64("Man"), "TWFu", "RFC 4648 vector")
equal(P.Decode64("not base64!"), nil, "invalid base64 rejected")
local legacy = P.ParseString(P.ExportString(P.Snapshot(), "Saved"))
equal(legacy.name, "Saved", "old profile codes read back their name")
equal(legacy.points.trinketDown, 0, "and their values")
local okShared, sharedMsg = CS.Import(P.ExportString({ points = { trinketDown = 7 }, weights = {}, specs = {}, options = {},
  flavor = "cata" }, "Friend's PvP"))
equal(okShared, true, "shared profile kept: " .. tostring(sharedMsg))
assert(find("Friend's PvP"), "kept under its exported name")
equal(CS.Import(P.ExportString(P.Snapshot(), "Old name"), "Jaina"), true, "a sender's name replaces the exported one")
assert(find("Jaina") and not find("Old name"), "listed under the sender")
equal(old.db.points.trinketDown, 0, "keeping imports does not apply them")
local count = #CS.Profiles("battlegrounds")
equal((CS.Import(P.Encode64("WB1;f=cata;p.trinketDown=abc"))), false, "invalid values are not kept")
equal(#CS.Profiles("battlegrounds"), count, "nothing stored on failure")
local window = P.ShowImport()
window.box:SetText(code)
window.actions.add.scripts.OnClick(window.actions.add)
equal(window.status.text, "Tester added to Profiles. Copy it into this character to use it.", "status line")
equal(#CS.Profiles("battlegrounds"), count + 1, "Add to profiles keeps the paste")
window.box:SetText("garbage")
window.actions.add.scripts.OnClick(window.actions.add)
equal(window.status.text, "not a Highground profile", "invalid paste reported")
equal(window.status.wbToken, "error", "error status colour")
local item = find("Tester")
equal(CS.Delete(item.source), true, "delete a profile")
equal(find("Tester"), nil, "deleted")
equal(CS.Delete(item.source), false, "deleting the last import twice is a no-op")
local customized = client("cata", { kit5277 = 0 })
equal(visible(customized:row("Evasion")), true, "existing custom spell values are visible on first open")
assert(customized:find("Button", "Hide spell overrides (1)"), "override count makes custom tuning visible")
