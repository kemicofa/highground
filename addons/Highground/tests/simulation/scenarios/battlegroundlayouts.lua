  local again = new("cata", sim.env.HighgroundDB, function(_, env) env.HighgroundCharDB = sim.env.HighgroundCharDB end)
  again:event("PLAYER_ENTERING_WORLD")
  assert(same(again.ns.Core.pos.point, { "TOPLEFT", "TOPLEFT", 40, -40 }), "the setup from before the edit")
  equal(again.ns.Core.pos.layoutEdit, nil)
end)

