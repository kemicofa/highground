local test, new, check = ...
local function equal(a, b, why) check(a, b, why or "value") end

local function setup(client, saved, configure)
  local sim = new(client or "cata", saved, configure)
  sim.rated = false
  sim:enemy("Enemy")
  return sim, sim.ns.Core, sim.ns.Options.Profiles, sim.ns.Options.Profiles.Layouts
end
local function same(a, b) return a[1] == b[1] and a[2] == b[2] and a[3] == b[3] and a[4] == b[4] end

test("a size's layout loads in its matches, remembers changes and gives the setup back afterwards", function()
  local sim, C, P, L = setup()
  C.pos.point = { "TOPLEFT", "TOPLEFT", 100, -100 }
  C.SetFeature("sniper", false)
  assert(L.Create("bg15"), "a layout starts from the current setup")
  C.SetFeature("sniper", true); C.pos.point = { "TOPLEFT", "TOPLEFT", 40, -40 }
  assert(P.SaveProfile("Main")); assert(P.LoadProfile("Main"))
  sim:join() -- unrated Arathi Basin: 15v15
  equal(L.Active(), "bg15", "applied on entry")
  equal(C.On("sniper"), false, "the layout's switches")
  assert(same(C.pos.point, { "TOPLEFT", "TOPLEFT", 100, -100 }), "and panel positions")
  equal(P.ActiveState().layout, "bg15", "the context bar names the layout")
  C.pos.point = { "CENTER", "CENTER", 5, 5 } -- moved during the match
  sim:leave()
  equal(L.Active(), nil)
  assert(same(L.Get("bg15").snap.setup.positions.point, { "CENTER", "CENTER", 5, 5 }), "the move is remembered")
  equal(C.On("sniper"), true, "the setup from before the match is back")
  assert(same(C.pos.point, { "TOPLEFT", "TOPLEFT", 40, -40 }), "with its positions")
  equal(C.db.activeProfile, "Main", "and its profile name")
  sim:join()
  assert(same(C.pos.point, { "CENTER", "CENTER", 5, 5 }), "the next match starts where the last one ended")
  sim:leave(); sim:assertHealthy()
end)

test("with Remember off a match leaves the layout as saved", function()
  local sim, C, P, L = setup()
  C.pos.point = { "TOPLEFT", "TOPLEFT", 100, -100 }
  L.Create("bg15"); L.SetRemember(false)
  sim:join()
  equal(P.ActiveState().status, "Changes not kept")
  C.pos.point = { "CENTER", "CENTER", 5, 5 }
  sim:leave()
  assert(same(L.Get("bg15").snap.setup.positions.point, { "TOPLEFT", "TOPLEFT", 100, -100 }), "unchanged")
end)

test("a reload during a match keeps the layout and the setup to restore", function()
  local sim, C, _, L = setup()
  C.SetFeature("sniper", false); L.Create("bg15"); C.SetFeature("sniper", true)
  sim:join()
  C.pos.point = { "CENTER", "CENTER", 7, 7 }
  sim:event("PLAYER_LOGOUT")
  local again = new("cata", sim.env.HighgroundDB, function(s, env) env.HighgroundCharDB = sim.env.HighgroundCharDB; s.rated = false end)
  again:enemy("Enemy"); again:join()
  local C2, L2 = again.ns.Core, again.ns.Options.Profiles.Layouts
  equal(L2.Active(), "bg15", "still applied")
  assert(same(C2.pos.point, { "CENTER", "CENTER", 7, 7 }), "the move survives")
  assert(same(L2.Get("bg15").snap.setup.positions.point, { "CENTER", "CENTER", 7, 7 }), "and was saved on logout")
  again:leave()
  equal(C2.On("sniper"), true, "the setup from before the match comes back after a reload")
  again:assertHealthy()
end)

test("a late rated flag switches layouts and leaving still restores the setup from before the match", function()
  local sim, C, _, L = setup()
  C.SetFeature("sniper", false); L.Create("bg15")
  C.SetFeature("sniper", true); C.SetFeature("pressure", false); L.Create("bg10")
  C.SetFeature("pressure", true)
  sim:join()
  equal(L.Active(), "bg15")
  sim.rated = true; sim:event("PVP_MATCH_STATE_CHANGED")
  equal(L.Active(), "bg10", "rated play is 10v10")
  equal(C.On("pressure"), false); equal(C.On("sniper"), true)
  sim:leave()
  equal(C.On("pressure"), true, "the setup from before the match, not the 15v15 layout")
end)

test("an Open world profile wins over restoring, and sizes without a layout or switched off don't switch", function()
  local sim, C, P, L = setup()
  C.SetFeature("sniper", false); assert(P.SaveProfile("World"))
  C.SetFeature("sniper", true)
  assert(P.Assign("World", "world")); C.pos.autoProfiles = true
  C.SetFeature("pressure", false); L.Create("bg15"); C.SetFeature("pressure", true)
  sim:join(); equal(L.Active(), "bg15")
  sim:leave()
  equal(C.db.activeProfile, "World", "the assigned Open world profile loads")
  equal(C.On("sniper"), false)
  C.pos.autoProfiles = false
  C.SetSizeEnabled("bg15", false); P.Automatic()
  C.SetFeature("pressure", true)
  sim:join()
  equal(L.Active(), nil, "Highground is off in this size, so its layout waits")
  equal(C.On("pressure"), true)
  sim:leave()
  C.SetSizeEnabled("bg15", true); P.Automatic()
  sim.rated = true; sim:join()
  equal(L.Active(), nil, "10v10 has no layout"); sim:leave()
end)

test("removing the layout in use restores the setup at once and does not save it again", function()
  local sim, C, _, L = setup()
  C.SetFeature("sniper", false); L.Create("bg15"); C.SetFeature("sniper", true)
  sim:join(); equal(C.On("sniper"), false)
  assert(L.Remove("bg15"))
  equal(L.Active(), nil); equal(L.Get("bg15"), nil, "gone")
  equal(C.On("sniper"), true, "the setup from before the match")
  sim:leave(); equal(L.Get("bg15"), nil, "leaving does not bring it back")
end)

test("entering in combat applies the layout after combat", function()
  local sim, C, P, L = setup()
  C.SetFeature("sniper", false); L.Create("bg15"); C.SetFeature("sniper", true)
  sim:setCombat(true); sim:join()
  equal(L.Active(), "bg15"); equal(C.On("sniper"), true, "waits for combat")
  assert(P.ActiveState().pending, "the bar says it applies after combat")
  equal(P.ActiveState().status, sim.ns.Locale:Get("profiles.context.pending"), "instead of the saving status")
  sim:setCombat(false)
  equal(C.On("sniper"), false, "applied")
  sim:leave(); equal(C.On("sniper"), true)
end)

test("assignments become per character and a Battlegrounds choice in use becomes size layouts", function()
  local sim, C, P, L = setup()
  C.SetFeature("sniper", false); P.SaveProfile("BG"); C.SetFeature("sniper", true)
  P.SaveProfile("Arena A"); P.SaveProfile("Arena B"); P.SaveProfile("World B")
  C.UpdateMe()
  local spec = tostring(C.me.specID or C.me.class or "unknown")
  local who = sim.ns.Scope.Character()
  C.db.profileAssignments = { [who] = { [spec .. ":arena"] = "Arena A", ["99999:arena"] = "Arena B",
    ["99999:world"] = "World B", [spec .. ":bg"] = "BG" } }
  C.pos.autoProfiles = true
  P.Automatic()
  local saved = C.db.profileAssignments[who]
  equal(saved.arena, "Arena A", "the current specialization's choice wins")
  equal(saved.world, "World B", "another specialization's choice fills a gap")
  equal(saved.bg, nil); equal(saved[spec .. ":arena"], nil, "old keys are gone")
  for _, bracket in ipairs({ "bg10", "bg15", "bg40" }) do
    equal(L.Get(bracket).snap.setup.features.sniper, false, bracket .. " starts from the Battlegrounds profile")
  end
  local off = new("cata")
  off.ns.Core.UpdateMe()
  local offSpec = tostring(off.ns.Core.me.specID or off.ns.Core.me.class or "unknown")
  off.ns.Options.Profiles.SaveProfile("BG")
  off.ns.Core.db.profileAssignments = { [off.ns.Scope.Character()] = { [offSpec .. ":bg"] = "BG" } }
  off.ns.Options.Profiles.Automatic()
  equal(off.ns.Options.Profiles.Layouts.Get("bg15"), nil, "a choice that was never switched on creates nothing")
end)

test("the sizes card creates, shows and removes layouts and switches Remember", function()
  local sim, C, P, L = setup()
  sim.ns.Hub.Open(sim.ns.Options.addonPages.battlegrounds.settings)
  local card = sim.ns.Options.featurePages.battlegrounds.sizes
  local row = card.rows[2]
  assert(row.create:IsVisible() and not row.remove:IsShown(), "Create layout before one exists")
  assert(row.note:GetText():find("usual setup", 1, true))
  row.create:Click()
  assert(L.Get("bg15") and row.remove:IsShown() and not row.create:IsShown(), "created")
  assert(row.note:GetText():find("own layout", 1, true))
  sim:join(); sim:event("ZONE_CHANGED_NEW_AREA")
  assert(row.note:GetText():find("in use", 1, true), "says it is in use")
  sim:leave(); sim:event("ZONE_CHANGED_NEW_AREA")
  row.remove:Click()
  assert(L.Get("bg15"), "the first click only arms")
  row.remove:Click()
  equal(L.Get("bg15"), nil, "the second removes")
  card.remember.toggle:Click()
  equal(C.pos.rememberLayouts, false, "Remember is saved for the character")
  C.SetSizeEnabled("bg40", false); card:Refresh()
  assert(not card.rows[3].create.enabled, "no layout for a size Highground is off in")
  C.SetFontScale(1.5); assert(card:Layout(320) > 0, "fits a narrow page with large text")
  sim:assertHealthy()
end)

test("Profiles points battlegrounds to the sizes card and the context bar opens it", function()
  local sim, C, P, L = setup()
  L.Create("bg15")
  sim.ns.Hub.Open("profiles")
  local a = sim.ns.Options.panel.assignments
  equal(a.activities.bg, nil, "no Battlegrounds profile picker")
  assert(a.sizes:IsVisible(), "a button to Battleground sizes instead")
  equal(a.scope:GetText(), sim.env.UnitName("player"), "scoped to the character only")
  a.sizes:Click()
  equal(sim.ns.Hub.current, sim.ns.Options.addonPages.battlegrounds.settings)
  sim.ns.Hub.win:Hide()
  sim:join()
  local state = P.CurrentState(true)
  equal(state.label, "Settings from: 15v15 battlegrounds layout")
  equal(state.status, "Changes saved to the layout")
  sim.ns.Hub.Open("profiles")
  local bar = sim.ns.Options.panel.profileContext
  assert(bar, "the profiles workspace has a context bar")
  bar.scripts.OnClick(bar)
  equal(sim.ns.Hub.current, sim.ns.Options.addonPages.battlegrounds.settings, "clicking it opens Battleground sizes")
  sim:leave(); sim:assertHealthy()
end)

test("/hg layout creates, lists and removes layouts and switches Remember like the card", function()
  local sim, C, _, L = setup()
  local function last() return sim.messages[#sim.messages - 1] end
  sim:command("layout")
  assert(last():find("no battleground layouts", 1, true), "status without layouts")
  sim:command("layout create 15")
  assert(L.Get("bg15"), "created")
  assert(last():find("15v15 battlegrounds", 1, true), "listed")
  sim:join(); sim:command("layout")
  assert(last():find("15v15 battlegrounds (in use)", 1, true), "marks the one in use")
  sim:leave()
  sim:command("layout remember off")
  equal(L.Remember(), false)
  assert(sim.messages[#sim.messages]:find("not kept", 1, true))
  sim:command("layout remove 15"); equal(L.Get("bg15"), nil, "removed")
  sim:command("layout remove 15")
  assert(sim.messages[#sim.messages]:find("no layout", 1, true), "says when there is nothing to remove")
  sim:command("layout create 99")
  assert(sim.messages[#sim.messages]:find("/hg layout create", 1, true), "usage")
end)
