test("/hg layout creates, lists and removes layouts and switches Remember like the card", function()
  local sim, C, _, L = setup()
  local function last() return sim.messages[#sim.messages - 1] end
  sim:command("layout")
  assert(last():find("no battleground layouts", 1, true), "status without layouts")
  sim:command("layout create 15")
  assert(L.Get("bg15"), "created")
  assert(last():find("15v15 battlegrounds", 1, true), "listed")
  sim:join(); sim:command("layout")
  assert(last():find("15v15 battlegrounds (in use)", 1, true), "marks the one in use")
  sim:leave()
  sim:command("layout remember off")
  equal(L.Remember(), false)
  assert(sim.messages[#sim.messages]:find("not kept", 1, true))
  sim:command("layout remove 15"); equal(L.Get("bg15"), nil, "removed")
  sim:command("layout remove 15")
  assert(sim.messages[#sim.messages]:find("no layout", 1, true), "says when there is nothing to remove")
  sim:command("layout create 99")
  assert(sim.messages[#sim.messages]:find("/hg layout create", 1, true), "usage")
end)

-- A second character on the same account, with its own layouts.
local function Alt(sim, name)
  local alt = new("cata", sim.env.HighgroundDB, function(s, env)
    env.HighgroundCharDB = {}; s.units.player.name = name; s.rated = false
  end)
  return alt, alt.ns.Core, alt.ns.Options.Profiles.Layouts
end

test("Copy from… takes another character's layouts or a saved profile, and applies a copy in use", function()
  local sim, C, P, L = setup()
  C.SetFeature("sniper", false); L.Create("bg15"); L.Create("bg40"); C.SetFeature("sniper", true)
  local alt, C2, L2 = Alt(sim, "Kemi")
  local list = L2.Characters()
  equal(#list, 1, "the other character is offered"); equal(list[1].name, "Me")
  equal(L2.Copy("bg15", { character = list[1].key }), 1)
  equal(L2.Get("bg15").snap.setup.features.sniper, false, "its 15v15 layout")
  equal(L2.Get("bg40"), nil, "only that size")
  equal(L2.Copy("bg10", { character = list[1].key, all = true }), 2, "every size it has")
  assert(L2.Get("bg40"))
  C2.SetFeature("pressure", false); P = alt.ns.Options.Profiles; P.SaveProfile("Calm"); C2.SetFeature("pressure", true)
  alt:enemy("Enemy"); alt:join(); equal(L2.Active(), "bg15")
  equal(L2.Copy("bg15", { profile = "Calm" }), 1)
  equal(C2.On("pressure"), false, "a copy into the layout in use applies at once")
  alt:leave(); equal(C2.On("pressure"), true, "and leaving still restores the setup from before")
  equal(L2.Copy("bg15", { profile = "Missing" }), 0, "unknown sources copy nothing")
  equal(L2.Copy("bg15", { character = L2.Key() }), 0, "not from yourself")
  alt:assertHealthy()
end)

test("the Copy from… window lists sources, explains what it replaces and copies", function()
  local sim, C, P, L = setup()
  C.SetFeature("sniper", false); L.Create("bg15"); L.Create("bg10")
  local alt, C2, L2 = Alt(sim, "Kemi")
  L2.Create("bg15")
  alt.ns.Hub.Open(alt.ns.Options.addonPages.battlegrounds.settings)
  local card = alt.ns.Options.featurePages.battlegrounds.sizes
  card.rows[2].copy:Click()
  local w = alt.env.HighgroundLayoutCopy
  assert(w and w:IsShown(), "opens")
  assert(w.sub:GetText():find("15v15 battlegrounds", 1, true), "names the size")
  equal(w.from:GetValue():sub(1, 2), "c:", "another character comes first")
  assert(w.all:IsShown() and w.all.desc:GetText():find("10v10 battlegrounds and 15v15 battlegrounds", 1, true), "lists its sizes")
  assert(w.warning:GetText():find("replaces", 1, true), "warns before replacing")
  w.all:Click(); w.copy:Click()
  assert(not w:IsShown(), "closes")
  equal(L2.Get("bg10").snap.setup.features.sniper, false, "copied every size")
  assert(alt.messages[#alt.messages]:find("Copied 2 layouts from Me", 1, true), "says what it did")
  equal(alt.ns.Hub.current, alt.ns.Options.addonPages.battlegrounds.settings, "back on the card")
  card.rows[3].copy:Click()
  equal(w.from:GetValue():sub(1, 2), "p:", "without another character's layout, profiles")
  assert(not w.all:IsShown() and w.warning:GetText() == "", "nothing to replace")
  w.cancel:Click(); equal(L2.Get("bg40"), nil, "Cancel copies nothing")
  alt:assertHealthy()
end)

test("Edit arranges a layout with sample panels for its size and puts the setup back", function()
  local sim, C, P, L = setup()
  C.pos.point = { "TOPLEFT", "TOPLEFT", 100, -100 }
  L.Create("bg40")
  C.pos.point = { "TOPLEFT", "TOPLEFT", 40, -40 }
  sim.ns.Hub.Open(sim.ns.Options.addonPages.battlegrounds.settings)
  local card = sim.ns.Options.featurePages.battlegrounds.sizes
  assert(card.rows[3].edit:IsShown() and not card.rows[1].edit:IsShown(), "Edit only for a size with a layout")
  card.rows[3].edit:Click()
  local S = sim.ns.Setup
  assert(S.placement and S.layoutBar:IsShown(), "placement starts")
  assert(S.layoutBar.title:GetText():find("Epic battlegrounds", 1, true), "titled for the size")
  local count = 0; for _ in pairs(C.enemies) do count = count + 1 end
  equal(count, 40, "a 40-player sample team")
  assert(same(C.pos.point, { "TOPLEFT", "TOPLEFT", 100, -100 }), "the layout's positions")
  equal(S.layoutBar.back:GetText(), "Cancel")
  C.pos.point = { "CENTER", "CENTER", 9, 9 } -- dragged
  S.layoutBar.finish:Click()
  assert(not S.placement and not C.testMode, "samples stop")
  assert(same(L.Get("bg40").snap.setup.positions.point, { "CENTER", "CENTER", 9, 9 }), "Done saves the layout")
  assert(same(C.pos.point, { "TOPLEFT", "TOPLEFT", 40, -40 }), "and puts the setup back")
  equal(C.pos.layoutEdit, nil)
  equal(sim.ns.Hub.current, sim.ns.Options.addonPages.battlegrounds.settings, "returns to the card")

  card.rows[3].edit:Click()
  C.pos.point = { "CENTER", "CENTER", 1, 1 }
  sim.ns.Setup.layoutBar.back:Click()
  assert(same(L.Get("bg40").snap.setup.positions.point, { "CENTER", "CENTER", 9, 9 }), "Cancel keeps the layout")
  assert(same(C.pos.point, { "TOPLEFT", "TOPLEFT", 40, -40 }))

  assert(S.BeginPlacement(false))
  equal(L.Edit("bg40"), false, "not while panels are already being placed"); S.EndPlacement(false)
  card.rows[3].edit:Click(); sim:setCombat(true)
  assert(not S.placement, "combat ends editing"); sim:setCombat(false)
  assert(same(C.pos.point, { "TOPLEFT", "TOPLEFT", 40, -40 }), "without saving")
  sim:join(); sim.ns.Hub.Open(sim.ns.Options.addonPages.battlegrounds.settings)
  assert(not card.rows[3].edit.enabled, "no editing during a match")
  equal(L.Edit("bg40"), false); sim:leave()
  sim:assertHealthy()
end)

test("an edit left open by a reload puts the setup back", function()
  local sim, C, _, L = setup()
  C.pos.point = { "TOPLEFT", "TOPLEFT", 100, -100 }; L.Create("bg15")
  C.pos.point = { "TOPLEFT", "TOPLEFT", 40, -40 }
