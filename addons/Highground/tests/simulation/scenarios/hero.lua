local test, new, equal = ...

for _, client in ipairs({ "cata", "retail" }) do
  for _, useDown in ipairs({ true, false }) do
    test(client .. " hero mouse target and focus with key-down " .. tostring(useDown), function()
      local sim = new(client)
      sim.useOnKeyDown = useDown
      local enemy = sim:enemy("Enemy")
      sim:join()
      sim:click("HighgroundHeroButton")
      equal(sim.units.target, enemy, "left click selects the shown enemy")
      equal(#sim.clickActions, 1, "mouse gesture fires exactly once")
      sim.units.target = nil
      sim:click("HighgroundHeroButton", "RightButton")
      equal(sim.units.focus, enemy, "right click focuses the shown enemy")
      equal(sim.units.target, nil, "focus preserves having no target")
      sim.units.target = sim.units.player
      sim:click("HighgroundHeroButton", "RightButton")
      equal(sim.units.target, sim.units.player, "focus restores the previous target")
      sim:click("HighgroundHeroButton", "LeftButton", true)
      equal(sim.units.target, sim.units.player, "shift-click only prepares a call")
      assert(sim.chatDraft:find("Enemy", 1, true), "call names the card's target")
    end)
  end
end

test("hero GO target, left click and target keybind agree before combat", function()
  local sim = new("cata")
  sim:enemy("Alpha")
  local beta = sim:enemy("Beta", { buffs = { { spellId = 45438, icon = 1 } } })
  sim:join()
  sim:command("points spent 2")
  sim:command("weight cooldowns 0")
  equal(sim.ns.Core.hero.name.text, "Alpha", "initial enemy selected")
  beta.buffs = {}
  sim:combatLog("SPELL_AURA_REMOVED", "Beta", "Beta", 45438)
  sim:advance(0.5)
  equal(sim.ns.Core.hero.name.text, "Beta", "GO window becomes the shown recommendation")
  sim:click("HighgroundHeroButton")
  equal(sim.units.target, beta, "hero click selects its displayed GO target")
  sim.units.target = nil
  sim:click("HighgroundTargetButton", "LeftButton", false, true)
  equal(sim.units.target, beta, "target keybind agrees with hero")
end)

test("combat hero names its actual click target when the recommendation changes", function()
  local sim = new("cata")
  local alpha = sim:enemy("Alpha")
  local beta = sim:enemy("Beta", { yards = 70 })
  sim:join()
  sim:setCombat(true)
  alpha.yards, beta.yards = 70, 20
  sim:advance(0.5)
  equal(sim.ns.GetKillNow().key, "Beta-Realm", "live recommendation still follows combat")
  equal(sim.ns.Core.hero.name.text, "Alpha", "card names the target its secure button can select")
  assert(sim.ns.Core.hero.clickNote.text:find("BETA", 1, true), "card also identifies the live recommendation")
  sim:click("HighgroundHeroButton")
  equal(sim.units.target, alpha, "combat click matches card name")
  sim:setCombat(false)
  equal(sim.ns.Core.hero.name.text, "Beta", "combat exit immediately refreshes the card")
  sim:click("HighgroundHeroButton")
  equal(sim.units.target, beta, "combat exit refreshes the secure action")
end)

test("first enemy appearing in combat cannot masquerade as a bound hero target", function()
  local sim = new("cata")
  local enemy = sim:enemy("Late", { yards = 70 })
  sim:join()
  sim:setCombat(true)
  enemy.yards = 20
  sim:advance(0.5)
  equal(sim.ns.GetKillNow().key, "Late-Realm", "late enemy is still recommended")
  equal(sim.ns.Core.hero.empty:IsShown(), true, "unbound card does not advertise a working target click")
  equal(sim.ns.Core.hero.empty.text, "Target click unavailable", "card explains the unavailable action")
  sim:click("HighgroundHeroButton")
  equal(sim.units.target, nil, "no insecure targeting fallback")
  sim:click("HighgroundRow1")
  equal(sim.units.target, enemy, "the already-bound enemy row still works during combat")
  sim:setCombat(false)
  equal(sim.ns.Core.hero.name.text, "Late", "hero becomes usable as combat ends")
end)

test("hero supports an up-only macro click with key-down enabled", function()
  local sim = new("cata")
  local enemy = sim:enemy("Enemy")
  sim:join()
  sim:click("HighgroundHeroButton", "LeftButton", false, true)
  equal(sim.units.target, enemy, "macro click executes the hero action")
end)

test("combat hero retains a safe display when its bound enemy disappears", function()
  local sim = new("cata")
  local _, token = sim:enemy("Gone")
  local beta = sim:enemy("Beta", { yards = 70 })
  sim:join()
  sim:setCombat(true)
  sim.units[token], beta.yards = nil, 20
  sim:advance(2)
  equal(sim.ns.Core.hero.name.text, "Gone", "missing unit does not silently change the click name")
  equal(sim.ns.Core.hero.dist.text, "--", "unreadable bound range stays unknown")
  assert(sim.ns.Core.hero.clickNote.text:find("BETA", 1, true), "visible enemy remains recommended")
  sim:setCombat(false)
  sim:click("HighgroundHeroButton")
  equal(sim.units.target, beta, "new target binds once combat ends")
end)

test("hero clicks retain the realm when enemies share a name", function()
  local sim = new("cata")
  sim:enemy("Twin", { yards = 70 })
  local other = sim:enemy("Twin", { realm = "OtherRealm", yards = 20 })
  sim.scores[3].name = "Twin-OtherRealm"
  sim:join()
  sim:click("HighgroundHeroButton")
  equal(sim.units.target, other, "exact macro selects the recommended realm")
end)
