local test, new, equal = ...

local function near(actual, expected, why)
  assert(math.abs(actual - expected) < 0.00001, why .. ": " .. tostring(actual) .. " ~= " .. tostring(expected))
end

for _, client in ipairs({ "cata", "retail" }) do
test(client .. " alpha transitions retarget continuously and stop their driver when idle", function()
  local sim = new(client)
  local M, T = sim.ns.Motion, sim.ns.Theme
  local region = T.Fill(sim.env.UIParent, "ARTWORK", "accent")
  region:SetAlpha(0)
  M.Alpha(region, 1, "page")
  local driver = sim.frames[#sim.frames]
  assert(driver:GetScript("OnUpdate"), "transition starts the shared driver")
  sim:advance(0.05)
  near(region:GetAlpha(), 1 - 0.75 ^ 3, "eased quarter-time value")
  M.Alpha(region, 1, "page")
  sim:advance(0.05)
  near(region:GetAlpha(), 0.875, "same target does not restart elapsed time")
  M.Alpha(region, 0, "exit")
  near(region:GetAlpha(), 0.875, "reversing preserves current alpha")
  sim:advance(0.05)
  assert(region:GetAlpha() > 0 and region:GetAlpha() < 0.875, "reverse progresses")
  local reversing = region:GetAlpha()
  M.Show(region, true, "hover")
  near(region:GetAlpha(), reversing, "second reversal has no jump")
  sim:advance(0.2)
  equal(region:GetAlpha(), 1, "exact endpoint")
  M.Show(region, false, "exit")
  sim:advance(0.04)
  M.Show(region, true, "hover")
  sim:advance(0.3)
  assert(region:IsShown() and region:GetAlpha() == 1, "stale hide never wins over re-entry")
  assert(not driver:GetScript("OnUpdate") and not driver:IsShown(), "idle has no update work")
  M.Show(region, false, "exit")
  M.Alpha(region, 0, "exit")
  sim:advance(0.2)
  assert(region:IsShown() and region:GetAlpha() == 0, "alpha-only retarget cancels a pending visibility change")
  region:SetAlpha(1)
  M.Alpha(region, 0, "page")
  M.Stop(region, 0.4)
  sim:advance(0.3)
  equal(region:GetAlpha(), 0.4, "cancelled transition cannot overwrite a new value")
  assert(not driver:GetScript("OnUpdate"), "cancelling the last transition sleeps the driver")
end)

test(client .. " press, disable and hide reset interaction feedback without delaying clicks", function()
  local sim = new(client)
  local Kit, M = sim.ns.Kit, sim.ns.Motion
  local clicks = 0
  local button = Kit.Button(sim.env.UIParent, "Apply", 100, 24, { onClick = function() clicks = clicks + 1 end })
  button:SetPoint("CENTER", 4, 6)
  button.scripts.OnEnter(button)
  sim:advance(0.04)
  assert(button.hover:GetAlpha() > 0 and button.hover:GetAlpha() < 1, "hover is eased")
  button.scripts.OnMouseDown(button)
  sim:advance(0.03)
  assert(button.pressed:GetAlpha() > 0 and button.pressed:GetAlpha() < 1, "press has its own feedback")
  button.scripts.OnMouseUp(button)
  button.scripts.OnClick(button)
  equal(clicks, 1, "action is synchronous")
  button:Disable()
  assert(not button.hover:IsShown() and not button.pressed:IsShown(), "disable clears decorative layers")
  assert(not M.IsPlaying(button.hover) and not M.IsPlaying(button.pressed), "disable cancels both transitions")
  button.scripts.OnEnter(button)
  button.scripts.OnMouseDown(button)
  assert(not button.hover:IsShown() and not button.pressed:IsShown(), "disabled input cannot restart feedback")
  button:Enable()
  button.scripts.OnEnter(button)
  button.scripts.OnMouseDown(button)
  button:Hide()
  button:Show()
  assert(not button.hover:IsShown() and not button.pressed:IsShown(), "reopening has no stuck press or hover")
  equal(button:GetWidth(), 100, "hit area width stays fixed")
  equal(button:GetHeight(), 24, "hit area height stays fixed")
  equal(button:GetScale(), 1, "no scale change")
  local _, x, y = button:GetPoint()
  equal(x, 4, "x anchor stays fixed"); equal(y, 6, "y anchor stays fixed")
end)

test(client .. " focus and selection update immediately while their decoration settles", function()
  local sim = new(client)
  local Kit, M = sim.ns.Kit, sim.ns.Motion
  local input = Kit.Input(sim.env.UIParent, 160, "Name")
  input:SetFocus()
  assert(input.focusLine:IsShown() and input.focusLine:GetAlpha() > 0, "focus is visible on the first frame")
  assert(M.IsPlaying(input.focusLine), "underline settles")
  input:ClearFocus()
  assert(not input.focusLine:IsShown() and not M.IsPlaying(input.focusLine), "blur clears immediately")
  local editor = Kit.Editor(sim.env.UIParent)
  editor.code:SetFocus()
  assert(editor.focusLine:IsShown(), "multiline editor shares the focus cue")
  editor.code:ClearFocus()
  assert(not editor.focusLine:IsShown(), "editor blur clears it")
  local toggle = Kit.Toggle(sim.env.UIParent, "Setting", { checked = false })
  equal(toggle.pressed:GetParent(), toggle.well:GetParent(), "press tint shares the checkbox backing's frame")
  toggle:SetChecked(true)
  assert(toggle:GetChecked() and toggle.mark:IsShown(), "checked state is immediate")
  toggle:SetChecked(false)
  assert(not toggle.mark:IsShown() and not M.IsPlaying(toggle.mark), "unchecked state cannot linger")
  toggle:SetChecked(true, true)
  assert(not M.IsPlaying(toggle.mark) and toggle.mark:GetAlpha() == 1, "silent refresh has no animation")
  local first, second = Kit.Tab(sim.env.UIParent, "First"), Kit.Tab(sim.env.UIParent, "Second")
  first:Select(true)
  sim:advance(0.03)
  first:Select(false); second:Select(true)
  assert(not first.line:IsShown() and second.line:IsShown(), "only the current tab has a marker")
  sim:advance(0.3)
  assert(not first.bg:IsShown() and second.bg:GetAlpha() == 1, "tab surfaces reach their final state")
end)

test(client .. " theme changes preserve transitions and reduced motion settles them in combat", function()
  local sim = new(client)
  local Core, T, M = sim.ns.Core, sim.ns.Theme, sim.ns.Motion
  sim:enemy("Alpha"); sim:join(); sim:setCombat(true)
  local b = sim.ns.Kit.Button(sim.env.UIParent, "Action")
  b.scripts.OnEnter(b)
  sim:advance(0.03)
  local alpha = b.hover:GetAlpha()
  T.Use("parchment")
  near(b.hover:GetAlpha(), alpha, "theme repaint does not restart motion")
  equal(b.hover.colorTexture[1], T.Rgb("overlayHover")[1], "in-flight layer uses the current palette")
  local secure = Core.rows[1]
  M.Alpha(secure, 0.8, "page")
  b.scripts.OnMouseDown(b)
  Core.SetReducedMotion(true)
  assert(not M.IsPlaying(b.pressed) and not M.IsPlaying(b.hover), "current feedback settles now")
  assert(not b.hover:IsShown() and b.pressed:GetAlpha() == 1, "pressed state is preserved")
  equal(secure:GetAlpha(), 0.8, "alpha can settle without changing secure geometry or visibility")
  assert(secure:IsShown(), "secure target remains shown")
  b.scripts.OnMouseUp(b)
  assert(not b.pressed:IsShown() and b.hover:GetAlpha() == 1, "future interactions are instant")
  Core.SetReducedMotion(false)
  assert(not M.IsPlaying(b.hover) and not M.IsPlaying(secure), "past interactions do not replay")
  M.Stop(secure, 1)
end)

test(client .. " dialog and hub entrances cancel cleanly and never multiply fades", function()
  local sim = new(client)
  local Kit, M, Hub = sim.ns.Kit, sim.ns.Motion, sim.ns.Hub
  local closed = 0
  local d = Kit.Dialog(nil, { onClose = function() closed = closed + 1 end })
  d:Show()
  assert(d:GetAlpha() >= 0.88 and M.IsPlaying(d), "new dialog is readable immediately")
  sim:advance(0.04)
  d.close.scripts.OnClick(d.close)
  assert(not d:IsShown() and not M.IsPlaying(d), "Close immediately cancels its entrance")
  equal(closed, 1, "close handler runs once")
  equal(d:GetAlpha(), 1, "hidden window has no leftover fade")
  d:Show(); sim:advance(0.3)
  equal(d:GetAlpha(), 1, "reopening completes normally")
  d:Hide()
  Hub.Open("home")
  assert(M.IsPlaying(Hub.win) and not M.IsPlaying(Hub.content), "initial hub entrance is not multiplied")
  sim:advance(0.3)
  Hub.Show("macros")
  assert(M.IsPlaying(Hub.content), "page change has a content transition")
  local macros = sim.ns.Macros.Window.win
  assert(not M.IsPlaying(macros) and macros:GetAlpha() == 1, "borrowed window does not add an entrance")
  sim:advance(0.04)
  local alpha = Hub.content:GetAlpha()
  Hub.Show("macros")
  near(Hub.content:GetAlpha(), alpha, "same page refresh does not restart the transition")
  Hub.win:Hide()
  assert(not M.IsPlaying(Hub.content) and Hub.content:GetAlpha() == 1, "closing cancels the page transition")
end)

test(client .. " choice menus visibly fade in without delaying actions or dismissal", function()
  local sim = new(client)
  local Kit, M, Core = sim.ns.Kit, sim.ns.Motion, sim.ns.Core
  local picked
  local anchor = Kit.Select(sim.env.UIParent, { menu = true, value = "a",
    choices = { { key = "a", label = "Alpha" }, { key = "b", label = "Beta" } },
    onChange = function(_, value) picked = value end })
  anchor.scripts.OnClick(anchor)
  local menu = Kit.Dropdown.Frame()
  equal(menu:GetAlpha(), 0, "opening starts transparent, not almost opaque")
  sim:advance(0.05)
  assert(menu:GetAlpha() > 0.3 and menu:GetAlpha() < 0.8, "opening remains perceptible after 50 ms")
  Kit.Dropdown.Select(2)
  Kit.Dropdown.Accept()
  equal(picked, "b", "selection runs during the entrance")
  assert(not menu:IsShown() and not M.IsPlaying(menu), "selection closes and cancels immediately")
  anchor.scripts.OnClick(anchor)
  equal(menu:GetAlpha(), 0, "reopening restarts a clean entrance")
  sim:advance(0.21)
  assert(menu:GetAlpha() == 1 and not M.IsPlaying(menu), "menu reaches full opacity in 200 ms")
  Kit.Dropdown.Hide()
  anchor.scripts.OnClick(anchor)
  sim:advance(0.03)
  Core.SetReducedMotion(true)
  assert(menu:GetAlpha() == 1 and not M.IsPlaying(menu), "reduced motion settles an opening menu now")
  Kit.Dropdown.Hide()
  anchor.scripts.OnClick(anchor)
  assert(menu:GetAlpha() == 1 and not M.IsPlaying(menu), "future openings are instant with reduced motion")
end)

test(client .. " autocomplete refreshes an open popup without replaying its entrance", function()
  local sim = new(client)
  local Kit, M = sim.ns.Kit, sim.ns.Motion
  local box = Kit.Input(sim.env.UIParent, 200, "Spell")
  Kit.Dropdown.Attach(box, function(before)
    return before, { { text = "Alpha" }, { text = "Beta" } }
  end)
  box:SetFocus()
  local menu = Kit.Dropdown.Frame()
  assert(menu:IsShown() and M.IsPlaying(menu), "first open has an entrance")
  sim:advance(0.04)
  local alpha = menu:GetAlpha()
  box:SetText("a")
  near(menu:GetAlpha(), alpha, "typing preserves the current entrance")
  sim:advance(0.3)
  box:SetText("ab")
  assert(not M.IsPlaying(menu) and menu:GetAlpha() == 1, "later typing leaves the menu steady")
  Kit.Dropdown.Hide()
  assert(not menu:IsShown() and not M.IsPlaying(menu), "dismissal is immediate")
end)
end

test("motion tokens fall back safely and zero durations settle immediately", function()
  local sim = new("retail")
  local T, M = sim.ns.Theme, sim.ns.Motion
  T.Register("motion-test", { motion = { hover = 0, press = -1, page = 0 / 0, enter = math.huge } })
  T.Use("motion-test")
  equal(T.Motion("hover"), 0, "zero is a valid motion preference")
  for _, key in ipairs({ "press", "page", "enter" }) do
    equal(T.Motion(key), sim.ns.Themes.highground.motion[key], "invalid " .. key .. " falls back")
  end
  local region = T.Fill(sim.env.UIParent, "ARTWORK", "accent")
  region:SetAlpha(0)
  M.Alpha(region, 1, "hover")
  assert(region:GetAlpha() == 1 and not M.IsPlaying(region), "zero duration has no deferred work")
  M.Alpha(region, 0, "page")
  region:Hide()
  sim:advance(0.02)
  assert(not M.IsPlaying(region), "hidden regions are removed from the driver")
end)
