local test, new, equal = ...

for _, client in ipairs({ "cata", "retail", "forever" }) do
  local function make(saved, geometry)
    return new(client == "cata" and "cata" or "retail", saved or {}, function(sim, env)
      if geometry then dofile("../../tools/wowsim/geometry.lua")(sim) end
      if client == "forever" then
        env.GetBuildInfo = function() return "1.60.1", "70532", "Oct 22 2026", 16001 end
      end
    end)
  end
  local function preview(sim, health)
    local enemy, unit = sim:enemy("Marked", { health = health or 100, maxHealth = 100 })
    sim.units.target = enemy
    sim:command("sniper test"); sim:advance(0.2)
    return sim.ns.Core.sniper, unit, enemy
  end

  test(client .. " head defaults replace untouched body settings without overriding custom placements", function()
    local fresh = make()
    local scope = preview(fresh)
    equal(fresh.ns.Core.db.sniperPlacement, "head", "new settings use approximate head placement")
    equal(scope.points[1][5], -24, "head default uses its matching height")
    assert(scope.pulse.group:IsPlaying(), "the default marker gently pulses even at full health")
    equal(scope.pulseAnimation.duration, 1.2, "idle pulse is slower than finishing cues")
    local old = make({ sniperVersion = 4, sniperPlacement = "body", sniperY = -62,
      profiles = { Default = { setup = { preferences = { sniperPlacement = "body", sniperY = -62 } } } } })
    equal(old.ns.Core.db.sniperPlacement, "head", "untouched old default upgrades to head")
    equal(old.ns.Core.db.sniperY, -24, "old default height upgrades with placement")
    equal(old.ns.Core.db.profiles.Default.setup.preferences.sniperPlacement, "head", "saved old default profiles upgrade too")
    old:command("sniper place body")
    equal(old.ns.Core.db.sniperY, -40, "body preset is raised by 22 UI pixels")
    local again = make(old.env.HighgroundDB)
    equal(again.ns.Core.db.sniperPlacement, "body", "an explicit body choice survives reload")
    equal(again.ns.Core.db.sniperY, -40, "raised body height survives reload")
    local custom = make({ sniperVersion = 4, sniperPlacement = "right", sniperY = 12, sniperAnimate = false })
    equal(custom.ns.Core.db.sniperPlacement, "right", "explicit side placements stay intact")
    equal(custom.ns.Core.db.sniperY, 12, "custom height stays intact")
    equal(custom.ns.Core.db.sniperAnimate, false, "a saved animation opt-out stays intact")
  end)

  test(client .. " skull toggles leave an independent, tintable reticle on the same target", function()
    local sim = make()
    local C, T = sim.ns.Core, sim.ns.Theme
    local scope, unit = preview(sim)
    assert(scope:IsVisible() and scope.skull:IsVisible())
    equal(scope:GetParent(), sim.env.UIParent, "never reparent to a nameplate")
    equal(scope.points[1][2], sim.plates[unit], "anchor to the selected target")
    for _, layer in ipairs({ "reticle", "skull", "aim" }) do
      assert(scope[layer].texture:find("assets\\sniper\\Sniper", 1, true), "load the actual " .. layer .. " texture")
    end
    local aimPoint = scope.aim.points[1]
    sim:command("sniper skull off")
    assert(not scope.skull:IsVisible() and scope.reticle:IsVisible() and scope.aim:IsVisible())
    equal(scope.aim.points[1], aimPoint, "aiming point stays fixed when the skull is removed")
    equal(C.db.sniper, true, "skull is not the marker's master switch")
    sim:command("sniper color cyan")
    equal(scope.reticle.vertexColor[2], C.SNIPER_COLORS.cyan[2], "custom rim color applies immediately")
    equal(scope.aim.vertexColor[1], T.Rgb("sniperAim")[1], "aiming glyph retains its signal color")
    sim:command("sniper skull invalid")
    equal(C.db.sniperSkull, false, "invalid input preserves the skull preference")
    equal(C.db.sniper, true, "invalid input cannot disable the whole marker")
    sim.ns.Hub.Open("battlegrounds-settings")
    local boxes = {}
    for _, cb in ipairs(sim.ns.Options.featureBoxes) do boxes[cb.key] = cb end
    sim.ns.Options.featurePages.battlegrounds.more.scripts.OnClick(sim.ns.Options.featurePages.battlegrounds.more)
    boxes.sniperSkull.scripts.OnClick(boxes.sniperSkull)
    assert(scope.skull:IsVisible(), "Features toggle applies to the live marker")
    sim:command("sniper")
    sim:advance(0.2)
    assert(not scope:IsVisible() and not boxes.sniperSkull.enabled and not boxes.sniperAnimate.enabled)
  end)

  test(client .. " marker animation stops when hidden and obeys reduced motion during combat", function()
    local sim = make()
    local C = sim.ns.Core
    local scope, unit = preview(sim, 20)
    local pulse = scope.pulse.group
    assert(pulse:IsPlaying())
    equal(pulse:GetParent(), scope, "pulse the visible marker as one cue")
    sim:command("sniper animate off")
    assert(not pulse:IsPlaying())
    equal(scope:GetAlpha(), 1, "animation off leaves a fully visible marker")
    sim:command("sniper animate on")
    assert(pulse:IsPlaying())
    sim:setCombat(true)
    C.SetReducedMotion(true)
    assert(not pulse:IsPlaying(), "accessibility stops the native group immediately")
    sim:command("go"); sim:advance(0.2)
    equal(scope:GetScale(), C.db.sniperScale, "kill opportunity stays steady with reduced motion")
    C.SetReducedMotion(false); sim:advance(0.2)
    assert(pulse:IsPlaying(), "visible ongoing cues resume")
    equal(scope:GetScale(), C.db.sniperScale, "kill-window cue never changes marker size or placement")
    equal(scope.pulseAnimation.duration, 0.4, "kill opportunity uses the fastest pulse")
    local plate = sim.plates[unit]
    sim.plates[unit] = nil; sim:advance(0.2)
    assert(not scope:IsVisible() and not pulse:IsPlaying(), "lost plate stops animation")
    sim.plates[unit] = plate; sim:advance(0.2)
    assert(scope:IsVisible() and pulse:IsPlaying(), "reacquired plate resumes the marker")
    sim:command("sniper test")
    assert(not scope:IsVisible() and not pulse:IsPlaying(), "ending preview cleans up")
  end)

  test(client .. " legacy style restores the original crosshair and saves without losing the new skull preference", function()
    local sim = make()
    local C = sim.ns.Core
    local scope = preview(sim, 20)
    equal(C.db.sniperStyle, "layered", "new and upgraded settings default to the new icon")
    assert(scope.reticle:IsVisible() and not scope.legacy:IsVisible())
    sim:command("sniper place left")
    local anchor = scope.points[1]
    sim.ns.Hub.Open("battlegrounds-appearance")
    local page = sim.ns.Options.byKey["battlegrounds-appearance"]
    local mini = page.sniperPreview
    -- Native WoW propagates ancestor visibility callbacks; this frame mock doesn't.
    mini:GetScript("OnShow")(mini)
    assert(mini:IsVisible() and mini.reticle:IsVisible() and mini.pulse.group:IsPlaying(), "dropdown has a live preview")
    equal(mini.points[1][2], page.sniperStyle, "preview sits beside the dropdown")
    equal(mini.points[1][3], "RIGHT", "preview is on its right side")
    local frames = #sim.frames
    page.sniperStyle:SetValue("legacy")
    assert(mini.legacy:IsVisible() and not mini.reticle:IsVisible(), "preview switches with the selected style")
    assert(scope.legacy:IsVisible() and not scope.reticle:IsVisible() and not scope.aim:IsVisible() and not scope.skull:IsVisible())
    equal(scope.points[1], anchor, "style switching keeps the target and placement")
    equal(#scope.legacyParts, 13, "original four crosshair arms, center dot and eight bracket arms")
    equal(scope.legacyParts[1]:GetWidth(), 4, "original crosshair thickness")
    equal(scope.legacyParts[1]:GetHeight(), 19, "original arm length")
    equal(scope.legacyParts[5]:GetWidth(), 5, "original center dot")
    sim:command("sniper color cyan")
    for _, part in ipairs(scope.legacyParts) do
      equal(part.texture, C.WHITE, "legacy needs no new artwork files")
      equal(part.vertexColor[2], C.SNIPER_COLORS.cyan[2], "legacy respects custom colour")
    end
    assert(scope.pulse.group:IsPlaying(), "legacy shares the health pulse")
    sim:command("sniper skull off"); sim:command("sniper skull on")
    assert(not scope.skull:IsVisible(), "legacy never overlays the new skull")
    equal(#sim.frames, frames, "style changes reuse the existing preview")
    sim:command("profile save Legacy marker")
    equal(sim.ns.Hub.current, "profiles", "saving opens the complete profile review")
    sim.ns.Hub.Open("battlegrounds-appearance")
    mini:GetScript("OnShow")(mini)
    frames = #sim.frames
    sim:command("sniper style layered")
    assert(scope.skull:IsVisible() and not scope.legacy:IsVisible(), "new icon restores its saved skull preference")
    assert(mini.skull:IsVisible() and not mini.legacy:IsVisible(), "preview restores the skull too")
    equal(#sim.frames, frames, "style changes reuse the existing preview")
    sim.ns.Hub.Open("battlegrounds-settings")
    mini:GetScript("OnHide")(mini)
    assert(not mini:IsVisible() and not mini.pulse.group:IsPlaying(), "hidden settings stop preview animation")
    sim:command("profile load Legacy marker"); sim:advance(0.2)
    assert(scope.legacy:IsVisible() and not scope.reticle:IsVisible(), "profiles restore legacy")
    local again = make(sim.env.HighgroundDB)
    local restored = preview(again, 20)
    assert(restored.legacy:IsVisible(), "reload preserves legacy")
    again:command("sniper style invalid")
    equal(again.ns.Core.db.sniperStyle, "legacy", "invalid input preserves style")
    equal(make({ sniperStyle = "invalid" }).ns.Core.db.sniperStyle, "layered", "invalid saved styles use the new default")
  end)

  test(client .. " skull and motion preferences survive profiles and reload without replacing custom colors", function()
    local sim = make({ sniperColor = "magenta", sniperSkull = false, sniperAnimate = false })
    local scope = preview(sim, 20)
    equal(sim.ns.Core.db.sniperColor, "magenta", "existing color survives the new gold default")
    assert(not scope.skull:IsVisible() and not scope.pulse.group:IsPlaying())
    sim:command("sniper place right"); sim:command("sniper padding 16")
    sim:command("sniper x 4"); sim:command("sniper y 10")
    sim:command("profile save Open sight")
    sim:command("sniper skull on"); sim:command("sniper animate on")
    sim:command("sniper place head"); sim:command("sniper padding 2")
    sim:command("profile load Open sight"); sim:advance(0.2)
    equal(sim.ns.Core.db.sniperSkull, false, "profile restores the skull choice")
    equal(sim.ns.Core.db.sniperAnimate, false, "profile restores the animation choice")
    equal(sim.ns.Core.db.sniperPlacement, "right", "profile restores placement")
    equal(sim.ns.Core.db.sniperPadding, 16, "profile restores padding")
    equal(sim.ns.Core.db.sniperY, 10, "profile restores custom height")
    assert(not scope.skull:IsVisible() and not scope.pulse.group:IsPlaying())
    local again = make(sim.env.HighgroundDB)
    local restored = preview(again, 20)
    assert(not restored.skull:IsVisible() and not restored.pulse.group:IsPlaying())
    equal(restored.points[1][1], "LEFT", "reload keeps the right-side anchor")
    equal(restored.points[1][4], 20, "reload keeps padding plus horizontal adjustment")
    local broken = make({ sniperSkull = "no", sniperAnimate = 4, sniperPlacement = "helmet",
      sniperX = "wrong", sniperPadding = -1 })
    equal(broken.ns.Core.db.sniperSkull, true, "damaged skull setting falls back")
    equal(broken.ns.Core.db.sniperAnimate, true, "damaged motion setting falls back")
    equal(broken.ns.Core.db.sniperColor, "gold", "new settings use the reference's gold rim")
    equal(broken.ns.Core.db.sniperPlacement, "head", "unknown placement falls back")
    equal(broken.ns.Core.db.sniperPadding, 8, "invalid padding falls back")
    equal(broken.ns.Core.db.sniperX, 0, "invalid horizontal adjustment falls back")
  end)

  test(client .. " finishing pulse follows health bands and ignores score alone or unknown health", function()
    local sim = make()
    local C = sim.ns.Core
    local scope, unit, enemy = preview(sim)
    local group = scope.pulse.group
    assert(group:IsPlaying(), "healthy targets have a gentle default pulse")
    equal(scope.pulseAnimation.duration, 1.2, "healthy targets use the idle rate")
    for _, band in ipairs({ { 50, 0.9, 0.8 }, { 30, 0.6, 0.65 }, { 15, 0.4, 0.55 } }) do
      enemy.health = band[1]; sim:advance(0.2)
      assert(group:IsPlaying(), "lower health activates the pulse")
      equal(scope.pulseAnimation.duration, band[2], "pulse accelerates toward death")
      equal(scope.pulseAnimation.toAlpha, band[3], "urgency increases contrast without disappearing")
    end
    local play, starts = group.Play, 0
    group.Play = function(self) starts = starts + 1; play(self) end
    enemy.health = 12; sim:advance(0.6)
    equal(starts, 0, "health polling in the same band does not restart a pulse")
    enemy.health = 80; sim:advance(0.2)
    assert(group:IsPlaying(), "healing returns to the default pulse")
    equal(scope.pulseAnimation.duration, 1.2, "healing ends the urgent rate")
    C.UpdateSniper({ plateUnit = unit, hpPct = 1, score = 99999, carrier = true }, false)
    equal(scope.pulseAnimation.duration, 1.2, "high score alone does not accelerate the pulse")
    C.UpdateSniper({ plateUnit = unit, hpPct = 0.1, immune = true }, true)
    assert(not group:IsPlaying(), "immune enemies do not advertise a finishing opportunity")
    enemy.health = { secret = true }; sim:advance(0.2)
    assert(group:IsPlaying() and scope.pulseAnimation.duration == 1.2, "restricted health uses the gentle pulse")
    C.UpdateSniper({ plateUnit = unit, hpPct = { secret = true } }, false)
    equal(scope.pulseAnimation.duration, 1.2, "restricted cached values do not imply urgency")
    enemy.maxHealth = 0; sim:advance(0.2)
    equal(scope.pulseAnimation.duration, 1.2, "unknown health uses the gentle pulse")
    sim:command("go"); sim:advance(0.2)
    assert(group:IsPlaying(), "a real GO cue can pulse even when health is unavailable")
    enemy.maxHealth, enemy.health = 100, 0; sim:advance(0.2)
    assert(not group:IsPlaying(), "zero-health targets do not keep pulsing")
  end)

  test(client .. " placement controls preserve legacy height and keep side gaps stable across sizes", function()
    local sim = make({ sniperY = -77, sniperVersion = 4 }, true)
    local C = sim.ns.Core
    local scope, unit = preview(sim)
    local plate = sim.plates[unit]
    plate:SetSize(160, 24); plate:SetPoint("CENTER", sim.env.UIParent, "CENTER", 0, 0)
    equal(scope.points[1][5], -77, "existing body placement survives upgrade")
    sim.ns.Hub.Open("battlegrounds-appearance")
    local page = sim.ns.Options.byKey["battlegrounds-appearance"]
    assert(not page.sniperRows.sniperPadding.stepper.plus:IsEnabled(), "gap is for plate edges")
    page.sniperPlacement:SetValue("left")
    local gap = page.sniperRows.sniperPadding.stepper.plus
    gap.scripts.OnClick(gap)
    equal(C.db.sniperPadding, 10, "settings control applies gap immediately")
    local left = sim.bounds(scope)
    local pb = sim.bounds(plate)
    assert(math.abs(left[1] + left[3] - (pb[1] - 10)) < 0.01, "left icon edge clears the plate")
    sim:command("sniper size 2"); sim:command("sniper y 8")
    left = sim.bounds(scope)
    assert(math.abs(left[1] + left[3] - (pb[1] - 10)) < 0.01, "scaling preserves the gap")
    assert(math.abs(left[2] + left[4] / 2 - (pb[2] + pb[4] / 2 - 8)) < 0.01, "height is independent of icon scale")
    page.sniperPlacement:SetValue("right")
    local right = sim.bounds(scope)
    assert(math.abs(right[1] - (pb[1] + pb[3] + 10)) < 0.01, "right placement mirrors left")
    equal(C.db.sniperY, 0, "new placement restores its default height")
    local point = scope.points[1]
    sim:command("sniper why")
    equal(scope.points[1], point, "diagnostics cannot move the marker")
    sim:command("sniper place above")
    local above = sim.bounds(scope)
    assert(math.abs(above[2] + above[4] - (pb[2] - 10)) < 0.01, "above uses an outside edge gap")
    sim:command("sniper place head")
    local head = sim.bounds(scope)
    assert(math.abs(head[2] + head[4] / 2 - (pb[2] + pb[4] + 24)) < 0.01, "head estimate sits just below the plate")
    sim:command("sniper place invalid")
    equal(C.db.sniperPlacement, "head", "unknown choices preserve placement")
    sim:command("sniper padding -20"); sim:command("sniper x 999")
    equal(C.db.sniperPadding, 0, "negative gap clamps to zero")
    equal(C.db.sniperX, 200, "extreme offsets clamp")
    assert(not C.SetSniperNumber("sniperX", 0 / 0), "NaN never reaches frame anchors")
    assert(not C.SetSniperNumber("sniperX", math.huge), "infinity never reaches frame anchors")
  end)

  test(client .. " missing, hidden, forbidden and rejected anchors hide the marker and recover", function()
    local sim = make()
    local scope, unit = preview(sim, 15)
    local plate = sim.plates[unit]
    plate:Hide(); sim:advance(0.2)
    assert(not scope:IsShown() and not scope.pulse.group:IsPlaying())
    plate:Show(); plate.IsForbidden = function() return true end; sim:advance(0.2)
    assert(not scope:IsShown())
    plate.IsForbidden = function() return false end
    local setPoint = scope.SetPoint
    scope.SetPoint = function() error("restricted anchor") end
    sim:advance(0.2)
    assert(not scope:IsShown() and not scope.anchor, "failed anchor is not cached")
    scope.SetPoint = setPoint; sim:advance(0.2)
    assert(scope:IsShown() and scope.pulse.group:IsPlaying(), "the next usable plate update recovers")
    sim:command("sniper place left")
    local enemy2, unit2 = sim:enemy("Next", { health = 80 })
    sim.units.target = enemy2; sim:advance(0.2)
    equal(scope.points[1][2], sim.plates[unit2], "changing target moves the side marker")
    equal(scope.pulseAnimation.duration, 1.2, "new healthy target does not inherit previous urgency")
  end)
