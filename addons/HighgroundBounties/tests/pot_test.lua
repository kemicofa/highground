test("live personal, guild and global rewards combine without counting linked copies twice", function()
  local a, g, h = F.new("Alice"), F.new("GuildPoster", { guild = "Watch", rank = 0 }), F.new("Hunter", { guild = "Watch", rank = 0 })
  F.post(a, nil, 300); F.deliver(a, h)
  assert(B(g).Add("Enemy", 400)); local guild = assert(B(g).Submit("Enemy"))
  assert(B(h).Merge(P(g).Copy(guild)))
  assert(B(h).Add("Enemy", 200))
  local pot = B(h).Pot.Find("Enemy")
  equal(pot.pledgedGold, 900); equal(#pot.contributions, 3)
  for _, scope in ipairs({ "mine", "guild", "public" }) do equal(B(h).BoardModel.Rows(scope)[1].gold, 900) end
  local linked = F.post(g, nil, 400)
  assert(P(h).Merge(P(g).Copy(linked), linked.by))
  B(h).Guild()["enemy-realm"].publicID = linked.id
  pot = B(h).Pot.Find("Enemy")
  equal(pot.pledgedGold, 900); equal(#pot.contributions, 3, "guild/shared reward paid once")
  P(h).Data().offers[linked.id].state = "withdrawn"
  equal(B(h).Pot.Find("Enemy").pledgedGold, 500, "closed rewards disappear")
  h.now = h.now + 15 * 86400
  equal(B(h).Pot.Find("Enemy"), nil, "expired personal and public rewards leave the live pot")
end)

