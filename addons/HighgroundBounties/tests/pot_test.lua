test("private pot links preserve every original and pending reports await the owner's approval", function()
  local a, c, h, d = F.new("Alice", { saved = {} }), F.new("Carol", { saved = {} }),
    F.new("Hunter", { saved = {} }), F.new("Don", { saved = {} })
  local first, second = assert(B(a).Add("Enemy", 500)), assert(B(c).Add("Enemy", 300))
  for _, original in ipairs({ { a, first }, { c, second } }) do
    local link = assert(B(original[1]).Exchange.Link(original[2], "private"))
    assert(B(h).Exchange.Import(assert(B(h).Exchange.Decode(link))))
  end
  equal(B(h).Pot.Find("Enemy").pledgedGold, 800)
  equal(#B(h).Pot.Find("Enemy").contributions, 2)
  local url = assert(B(h).Exchange.Link(B(h).Personal()["enemy-realm"], "private"))
  assert(B(d).Exchange.Import(assert(B(d).Exchange.Decode(url))))
  equal(B(d).BoardModel.Rows("mine")[1].gold, 800)
  equal(#B(d).Pot.Find("Enemy").contributions, 2, "one private map entry cannot overwrite another poster")
  assert(B(h).Pot.Claim(B(h).Pot.Find("Enemy"), P(h).Now(), "manual report", true))
  equal(B(h).Pot.Find("Enemy").pledgedGold, 800, "pending reports do not close an imported pot")
  F.deliver(h, a)
  equal(#B(a).Ledger.All(), 1)
  equal(B(a).Pot.Find("Enemy").pledgedGold, 500, "original stays live until its owner decides")
  assert(B(a).Terms.Progress(first):find("pending review", 1, true))
  assert(B(a).Ledger.Change(B(a).Ledger.All()[1], "approved"))
  equal(B(a).Pot.Find("Enemy"), nil)
  F.deliver(a, h)
  equal(B(h).Pot.Find("Enemy").pledgedGold, 300, "the hunter receives closure of the private original")
  for _, c in ipairs(B(h).Ledger.All()) do if c.by == B(a).Me() then equal(c.state, "approved") end end
  assert(B(d).Remove("Enemy", "personal")); equal(B(d).Pot.Find("Enemy"), nil, "removing imports removes every original")
  equal(P(d).Receiving(), false); equal(P(d).Publishing(), false)
end)

