  packets = F.flush(b); F.deliver(b, a, packets); F.deliver(b, h, packets)
  assert(P(h).Claim("Enemy")); packets = F.flush(h); F.deliver(h, a, packets); F.deliver(h, b, packets)
  local debt = assert(claimFor(b, contribution.id))
  equal(P(b).ChangeClaim(debt, "approved"), false); equal(P(b).ChangeClaim(debt, "rejected"), false)
  local forged = P(b).Copy(debt)
  forged.state, forged.revision, forged.reviewedBy, forged.decision = "approved", 2, original.by, "fake-decision"
  equal(P(h).ReceiveClaim(forged, contribution.by), false, "a contributor cannot forge the original's acceptance")
  assert(P(a).ChangeClaim(claimFor(a, original.id), "approved"))
  packets = F.flush(a); F.deliver(a, b, packets); F.deliver(a, h, packets)
  equal(debt.state, "approved")
  F.deliver(b, h); equal(claimFor(h, contribution.id).state, "approved")
  assert(P(b).ChangeClaim(debt, "paid")); F.deliver(b, h)
  equal(claimFor(h, contribution.id).state, "paid")
end)

