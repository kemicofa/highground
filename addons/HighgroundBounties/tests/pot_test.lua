test("owner acceptance creates the contributor's debt even without a separate claim delivery", function()
  local a, b, h = F.new("Alice"), F.new("Bob"), F.new("Hunter")
  local original = F.post(a)
  local packets = F.flush(a); F.deliver(a, b, packets); F.deliver(a, h, packets)
  local contribution = assert(B(b).Pot.Add(P(b).Data().offers[original.id], 300, true))
  F.deliver(b, a) -- Hunter only knows the original reward.
  assert(P(h).Claim("Enemy")); F.deliver(h, a)
  assert(P(a).ChangeClaim(claimFor(a, original.id), "approved"))
  packets = F.flush(a); F.deliver(a, b, packets); F.deliver(a, b, packets); F.deliver(a, h, packets)
  local debt = assert(claimFor(b, contribution.id))
  equal(debt.state, "approved"); equal(debt.gold, 300); equal(debt.claimant, "Hunter-Realm")
  equal(debt.reviewedBy, "Alice-Realm"); equal(contribution.killsAwarded, 1, "retries cannot duplicate awards")
  equal(P(b).ChangeClaim(debt, "rejected"), false)
  equal(P(b).Withdraw(contribution), nil)
  F.deliver(b, h); P(b).RetryClaims(); F.deliver(b, h)
  equal(assert(claimFor(h, contribution.id)).state, "approved", "hunter learns about a previously unknown contributor's debt")
  assert(P(b).ChangeClaim(debt, "paid")); equal(contribution.state, "paid")
  F.deliver(b, h); equal(claimFor(h, contribution.id).state, "paid")
  equal(debt.reviewedBy, "Alice-Realm", "recording payment preserves the original completion reviewer")
  a:assertHealthy(); b:assertHealthy(); h:assertHealthy()
end)

test("a pending contributor claim cannot override the owner's decision and payment reaches the hunter", function()
  local a, b, h = F.new("Alice"), F.new("Bob"), F.new("Hunter")
  local original = F.post(a)
  local packets = F.flush(a); F.deliver(a, b, packets); F.deliver(a, h, packets)
