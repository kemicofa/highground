test("shared publishing is explicit, validates before opt-in, and keeps one target", function()
  local s = F.new("Alice", { saved = {} })
  local B = s.ns.Bounty
  local personal = assert(B.Add("Enemy-Other", 500, "flight master"))
  B.Board.Open()
  local row = B.Board.win.rows[1]
  row.more.scripts.OnClick(row.more)
  equal(s.ns.Kit.Dropdown.Items()[1].text, "Publish on shared board", "direct destination")
  s.ns.Kit.Dropdown.Accept(1)
  local w = B.Form.win
  equal(w.formMode, "public", "audience selected")
  equal(w.gold:GetText(), "500", "reward carried into draft")
  equal(w.note:GetText(), personal.note, "context retained")
  equal(P(s).Publishing(), false, "opening a draft never opts in")
  assert(w.action:IsEnabled(), "no disabled prerequisite")
  equal(w.action:GetText(), "Enable sharing & publish", "consent in final action")
  w.gold:SetText("9999999"); w.action.scripts.OnClick(w.action)
  equal(P(s).Publishing(), false, "invalid draft does not opt in")
  assert(w.error:GetText():find("Insufficient", 1, true), "visible inline error")
  w.gold:SetText("500"); w.duration:SetText("2h"); w.action.scripts.OnClick(w.action)
  local pledge = assert(P(s).Own(personal.name))
  equal(P(s).Publishing(), true, "final action enables publishing")
  equal(P(s).Receiving(), false, "publishing is independent from receiving")
  equal(pledge.expiresAt - P(s).Now(), 7200, "chosen duration")
  equal(#B.BoardModel.Rows("mine"), 1, "publication replaces private draft")
  equal(B.BoardModel.Rows("mine")[1].visibility, "Shared", "audience visible")
  local prefs = B.Preferences.Open()
  prefs.receive:SetChecked(true)
  prefs.threshold:SetFocus(); prefs.threshold:SetText("800"); prefs.threshold:ClearFocus()
  equal(s.ns.Core.O("bountyMinGold"), 800, "alert minimum saved")
  P(s).OpenDetails("Enemy-Other")
  assert(B.Details.win.cards[1].detail.text:find("Funds reported available", 1, true))
  assert(B.Details.win.terms.text:find("reviews their own reward", 1, true))
  assert(P(s).Post("Enemy-Other", 800, "4h", "updated"))
  P(s).Fill(personal.name, personal)
  equal(w.gold:GetText(), "800", "current contribution takes priority over old draft")
  P(s).Fill("Another-Other")
  equal(w.gold:GetText(), "", "unrelated target does not inherit reward")
  equal(w.note:GetText(), "", "unrelated target does not inherit terms")
  s:assertHealthy()
end)

for _, client in ipairs({ "retail", "cata" }) do
  test(client .. ": discovery synchronizes online posters and failed sends are retried", function()
    local a, h = F.new("Alice", { client = client }), F.new("Hunter", { client = client })
    local p = F.post(a)
    if client == "cata" then
      assert(a.chat[1] and a.chat[1].channel == "CHANNEL", "dedicated chat discovery")
      a:event("CHAT_MSG_CHANNEL", h.chat[1].text, h.ns.Bounty.Me(), "", "", "", "", "", 1, P(a).CHANNEL)
      a:advance(11)
      for _, packet in ipairs(a.sent) do assert(packet.channel ~= "CHANNEL", "Classic data uses whispers") end
    else P(a).Peer(h.ns.Bounty.Me()); a:advance(11) end
    h.now = a.now
    F.deliver(a, h, a.sent); F.deliver(a, h)
    equal(P(h).Find("Enemy").gold, 500, "late join gets author snapshot")
    P(a).QueueOffer(p, h.ns.Bounty.Me()); a.sendResult = 3
    P(a).Flush(); assert(#P(a).outbox > 0, "throttled send retained")
    a.sendResult = 0; F.deliver(a, h)
    equal(P(h).Find("Enemy").gold, 500, "retry remains idempotent")
  end)
end

