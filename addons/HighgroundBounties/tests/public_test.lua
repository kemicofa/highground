test("sharing is explicitly off by default and opt-out leaves the channel", function()
  local s = F.new("Alice", { saved = {} })
  equal(s.joins, 0, "no channel before consent")
  equal(#s.sent, 0, "no messages before consent")
  equal(P(s).Post("Enemy", 100, "2h"), nil, "cannot publish without consent")
  s:slash("HIGHGROUNDBOUNTIES", "shared receive on")
  equal(s.joins, 1, "receive opt-in joins")
  equal(P(s).Publishing(), false, "publishing is independent")
  s:slash("HIGHGROUNDBOUNTIES", "shared receive off")
  equal(s.leaves, 1, "opt-out leaves")
  equal(#P(s).outbox, 0, "queued sends discarded")
end)

test("account identity survives reloads and alts without duplicating a target", function()
  local a = F.new("Alice")
  local offer = F.post(a)
  local alt = F.new("Alt", { network = P(a).Copy(P(a).db) })
  equal(P(alt).db.id, P(a).db.id, "persistent account-wide contributor")
  equal(P(alt).Post("Enemy", 800, "4h"), nil, "alt cannot add a second contribution or spend Alice's gold")
  local again = F.new("Alice", { network = P(a).Copy(P(a).db) })
  local updated = F.post(again, "Enemy", 800, "4h")
  equal(updated.id, offer.id, "updates retain pledge identity")
  equal(updated.revision, 2, "updates advance revision")
  equal(F.count(P(again).Data().offers), 1, "one contribution")
end)

test("different contributors stack; duplicate and reordered wire messages do not", function()
  local a, b, hunter = F.new("Alice"), F.new("Bob"), F.new("Hunter")
  F.post(a, "Iron Fist-Other", 500, "2h")
  F.post(b, "Iron Fist-Other", 1000, "1d")
  local packets = F.flush(a)
  local reverse = {}; for i = #packets, 1, -1 do reverse[#reverse + 1] = packets[i] end
  F.deliver(a, hunter, reverse); F.deliver(a, hunter, packets); F.deliver(b, hunter)
  equal(P(hunter).Find("Iron Fist-Other").gold, 1500, "summed once")
  equal(#P(hunter).Find("Iron Fist-Other").contributions, 2, "two contributors")
  equal(P(hunter).Find("Iron Hands-Other"), nil, "never matches only a first name")
  equal(P(hunter).Find("Iron Fist-Realm"), nil, "never merges realms")
  F.post(a, "Iron Fist-Other", 600, "3h"); F.deliver(a, hunter)
  F.deliver(a, hunter, packets)
  equal(P(hunter).Find("Iron Fist-Other").gold, 1600, "stale revision cannot revert an edit")
end)

test("each pledge expires independently and stale funds never count as available", function()
  local a, b, h = F.new("Alice"), F.new("Bob"), F.new("Hunter")
  F.post(a, nil, 500, "5m"); F.post(b, nil, 1000, "2h")
  F.deliver(a, h); F.deliver(b, h)
  h.now = h.now + 301
  equal(P(h).Find("Enemy").gold, 0, "offline funding has become unknown")
  equal(P(h).Find("Enemy").pledgedGold, 1000, "expired pledge excluded from total")
  equal(P(h).Funds(P(h).Find("Enemy").contributions[1]), "unknown", "unknown is not insufficient")
  b.now = h.now; P(b).CheckFunds(true); F.deliver(b, h)
  equal(P(h).Find("Enemy").gold, 1000, "fresh author heartbeat restores eligible contribution")
end)

test("one gold budget covers all pledges, pending claims and the expiry grace period", function()
  local a = F.new("Alice", { gold = 1000 })
  local first = F.post(a, "First", 800, "5m")
  equal(P(a).Post("Second", 800, "2h"), nil, "no double allocation")
  F.post(a, "Second", 200, "2h")
  a.money = 900 * 10000; a:event("PLAYER_MONEY")
  equal(P(a).Funds(first), "available", "oldest pledge retains priority")
  equal(P(a).Funds(P(a).Own("Second")), "insufficient", "newer pledge underfunded")
  assert(F.said(a, "Insufficient funds") > 0, "poster notified")
  a.money = 1000 * 10000; a:event("PLAYER_MONEY")
  equal(P(a).Funds(P(a).Own("Second")), "available", "funding recovery")
  a.now = a.now + 301
  equal(P(a).Available(), 0, "expired pledge reserved during claim window")
  a.now = a.now + P(a).CLAIM_WINDOW
  equal(P(a).Available(), 800 * 10000, "unused reservation released after claim window")
  a.money = nil
  equal(P(a).Post("Third", 1, "2h"), nil, "unreadable funds cannot publish")
end)

test("receivers see later funding shortfalls and exact threshold crossings alert once", function()
  local a, b, h = F.new("Alice"), F.new("Bob"), F.new("Hunter")
  h.ns.Core.SetOption("bountyMinGold", 1000)
  h:advance(13); a.now = h.now; b.now = h.now
  F.post(a, nil, 600); F.deliver(a, h); h:advance(1)
  equal(F.said(h, "Shared bounty:"), 0, "below threshold")
  F.post(b, nil, 400); F.deliver(b, h); h:advance(1)
  equal(F.said(h, "Shared bounty:"), 1, "combined threshold crossed")
  P(b).CheckFunds(true); F.deliver(b, h); h:advance(1)
  equal(F.said(h, "Shared bounty:"), 1, "heartbeat is not a new bounty")
  a.money = 0; a:event("PLAYER_MONEY"); F.deliver(a, h); h:advance(1)
  equal(P(h).Find("Enemy").gold, 400, "receiver total decreases")
  equal(P(h).Find("Enemy", true), nil, "sightings respect eligible total")
  a.money = 10000 * 10000; a:event("PLAYER_MONEY"); F.deliver(a, h); h:advance(1)
  equal(F.said(h, "Shared bounty:"), 1, "cooldown prevents funding-flap spam")
end)

test("author checks, malformed packets, scope and tombstones block forged or stale changes", function()
  local a, h, evil = F.new("Alice"), F.new("Hunter"), F.new("Mallory")
  local offer = F.post(a)
  local packets = F.flush(a); F.deliver(a, h, packets)
  local fake = P(a).Copy(offer); fake.gold = 9000; fake.revision = fake.revision + 1
  equal(P(h).Merge(fake, evil.ns.Bounty.Me()), false, "ID does not authorize another sender")
  P(evil).Enqueue("offer", fake); F.deliver(evil, h)
  equal(P(h).Find("Enemy").gold, 500, "wire also checks actual sender")
  P(h).ReceivePart("1:x:1:999999:malformed", "Alice-Realm")
  equal(F.count(P(h).incoming), 0, "oversized input not buffered")
  local elsewhere = F.new("Other", { realm = "OtherRealm" }); F.deliver(a, elsewhere, packets)
  equal(#P(elsewhere).All(), 0, "different realm scope")
  assert(P(a).Withdraw(offer)); F.deliver(a, h); F.deliver(a, h, packets)
  equal(P(h).Find("Enemy"), nil, "old snapshot cannot resurrect withdrawal")
  local h2 = F.new("OptedOut", { saved = {} }); F.deliver(a, h2, packets)
  equal(F.count(P(h2).Data().offers), 0, "opt-out ignores unsolicited packets")
end)

