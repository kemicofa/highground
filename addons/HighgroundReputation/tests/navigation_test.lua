local t = dofile("../../tools/harness.lua")("reputation navigation")
local F = dofile("tests/fixture.lua")
local bg = dofile("../../tools/wowsim/battleground/runtime.lua")

for _, addon in ipairs({ "Highground", "HighgroundReputation" }) do
  for _, case in ipairs({ { "retail", 120100 }, { "retail", 16001 }, { "cata", 40402 } }) do
    t.test(addon .. " " .. case[2] .. ": tabs, organization guards and child dialogs share routing", function()
      local s = F.new("Owner", { addon = addon, client = case[1], build = case[2],
        guild = case[1] == "cata" and "Test Guild" or nil, runtime = addon == "Highground" and bg or nil })
      local W = F.W(s)
      local c = F.community(s)
      for i = 1, 20 do
        local name = "Enemy" .. (case[2] == 16001 and " Bright" or "") .. string.char(64 + i) .. "-Realm"
        W.Decide(c, F.target(s, name), "ban", { toxic = true }, "")
      end
      if s.ns.Hub then s.ns.Options.OpenTool("reputation") else W.Open() end
      local UI, w = W.UI, W.UI.window
      local router = UI.GetRouter()
      UI.SetMode("blacklist", c.id)
      w.search:SetText("Enemy")
      local stop = router:BeforeEach(function() return false end)
      F.click(s, w.tabs.settings)
      t.equal(w.workspaceTabs.selected, "organizations", "blocked Preferences keeps workspace selection")
      t.equal(w.pageTabs.selected, "blacklist", "blocked Preferences keeps the organization page")
      F.click(s, w.next); t.equal(UI.page, 1, "page control obeys navigation guards")
      stop(); F.click(s, w.next)
      local page = UI.page
      assert(page > 1, "list has more than one page")
      F.click(s, w.routeBack); t.equal(UI.page, 1, "Back returns to previous list page")
      t.equal(w.search:GetText(), "Enemy", "page navigation keeps search")
      F.click(s, w.routeForward); t.equal(UI.page, page, "Forward returns to next list page")
      F.click(s, w.tabs.settings)
      t.equal(w.workspaceTabs.selected, "settings", "Preferences is a workspace tab")
      assert(w.workspaceTabs:IsVisible() and not w.pageTabs:IsVisible(), "workspace tabs persist above preferences")
      assert(not w.previous:IsShown() and not w.next:IsShown(), "Preferences has no list pagination")
      F.click(s, w.routeBack)
      t.equal(UI.mode, "blacklist", "Back selects prior tab")
      t.equal(w.search:GetText(), "Enemy", "filter recovered")
      t.equal(UI.page, page, "page recovered")
      local visits = #router:History()
      for _ = 1, 3 do
        assert(UI.SetMode("blacklist", c.id))
        t.equal(w.search:GetText(), "Enemy", "selected tab retains filter")
        t.equal(UI.page, page, "selected tab retains page")
        t.equal(#router:History(), visits, "selected tab does not duplicate history")
        assert(router:CanGo(1), "selected tab preserves Forward")
      end
      F.click(s, w.routeForward); t.equal(UI.mode, "settings", "Forward selects settings")
      local visits = #router:History()
      w.replyText:SetText("My reply")
      F.click(s, w.tabs.settings)
      t.equal(w.replyText:GetText(), "My reply", "selected Preferences preserves edits")
      t.equal(#router:History(), visits, "selected Preferences adds no history")
      F.click(s, w.workspaceTabs.buttons.organizations)
      t.equal(UI.mode, "blacklist", "Organizations restores the page left before Preferences")
      t.equal(w.search:GetText(), "Enemy", "workspace return restores search")
      t.equal(UI.page, page, "workspace return restores pagination")
      F.click(s, w.tabs.members); w.search:SetText("Owner")
      F.click(s, w.tabs.blacklist)
      t.equal(w.search:GetText(), "Enemy", "organization tabs restore their own search")
      t.equal(UI.page, page, "organization tabs restore their own page")
      F.click(s, w.tabs.proposals); w.search:SetText("Previous search")
      F.click(s, w.tabs.blacklist); UI.SetMode("proposals", c.id)
      t.equal(w.search:GetText(), "", "explicit actions open a fresh list without restoring old filters")
      F.click(s, w.tabs.blacklist)
      F.click(s, w.tabs.settings)
      W.OpenReport(F.target(s, case[2] == 16001 and "New Enemy-Realm" or "NewEnemy-Realm"), c)
      local report, windows = UI.report, s.ns.Kit.Windows
      report.note:SetText("Unsaved report")
      t.equal(windows.router:Current().name, windows.entries[report].route, "report uses window routing")
      local nested = s.ns.Kit.CopyBox(nil, { title = "Review context" })
      nested:Open(); nested:Hide()
      assert(report:IsVisible(), "nested dialog returns to report")
      t.equal(report.note:GetText(), "Unsaved report", "draft survives nested dialog")
      report:Hide()
      assert(w:IsVisible(), "report returns to workspace")
      t.equal(UI.mode, "settings", "tab survives report")
      W.Disable(c)
      assert(router:Back())
      t.equal(router:Current().name, "overview", "history redirects to explicit resume when organization is disabled")
      t.equal(UI.mode, "overview", "unavailable tab never displayed")
      t.equal(W.db.selected, c.id, "paused organization stays selected")
      s:assertHealthy()
    end)

    t.test(addon .. " " .. case[2] .. ": workspace tabs restore scroll and compact menus keep access rules", function()
      local runtime = addon == "Highground" and bg or dofile("../../tools/wowsim/runtime.lua")
      local s = F.new("Owner", { addon = addon, client = case[1], build = case[2],
        guild = case[1] == "cata" and "Test Guild" or nil,
        runtime = function(client, settings, configure)
          return runtime(client, settings, function(sim, env)
            configure(sim, env); dofile("../../tools/wowsim/geometry.lua")(sim)
          end)
        end })
      local W = F.W(s)
      local w = W.Open()
      w:SetHeight(550)
      F.click(s, w.tabs.settings)
      t.equal(W.UI.mode, "settings", "preferences need no followed organization")
      local offset = math.min(60, w.settingsBody:GetHeight() - w.settings:GetHeight())
      assert(offset > 0, "preferences overflow the short workspace")
      w.settings:SetVerticalScroll(offset)
      F.click(s, w.workspaceTabs.buttons.organizations)
      t.equal(W.UI.mode, "organizations", "no prior organization returns to directory")
      F.click(s, w.tabs.settings)
      t.close(w.settings:GetVerticalScroll(), offset, "preferences scroll survives workspace switching")
      F.click(s, w.routeBack); F.click(s, w.routeForward)
      t.close(w.settings:GetVerticalScroll(), offset, "history also restores the preferences scroll")
      local c = F.community(s)
      W.UI.SetMode("overview", c.id)
      local overviewOffset = math.min(40, w.overviewBody:GetHeight() - w.overview:GetHeight())
      assert(overviewOffset > 0, "overview overflows the short workspace")
      w.overview:SetVerticalScroll(overviewOffset)
      F.click(s, w.tabs.settings)
      t.close(w.settings:GetVerticalScroll(), offset, "personal Preferences scroll follows a new organization context")
      F.click(s, w.workspaceTabs.buttons.organizations)
      t.close(w.overview:GetVerticalScroll(), overviewOffset, "Overview scroll is independent of Preferences")
      w.pageTabs:SetWidth(180); w.pageTabs:Layout()
      assert(w.pageTabs.compact, "narrow strips use the shared page menu")
      F.click(s, w.pageTabs.menu)
      assert(s.ns.Kit.Dropdown.Accept(3)); t.equal(W.UI.mode, "proposals", "compact destination navigates through Reputation")
      W.Disable(c); W.UI.SetMode("overview", c.id)
      F.click(s, w.pageTabs.menu)
      assert(not s.ns.Kit.Dropdown.Accept(3), "paused organization cannot open a disabled list")
      t.equal(W.UI.mode, "overview", "disabled menu keeps Overview selected")
      w:Hide()
      -- The simulator fires OnHide only on the direct owner, unlike WoW.
      -- Its existing popup visibility check also retires inherited closes.
      s:advance(0.01)
      assert(not s.ns.Kit.Dropdown.IsShown(), "workspace close retires the page menu")
      s:assertHealthy()
    end)
  end
end

t.finish("Reputation navigation: " .. t.tests .. " scenarios")
