"""Build the poster's compact titling fonts and WoW textures.

Requires fontTools and ImageMagick; no dependency is used by the addon.
The source font and generated paper are kept in assets/wanted-poster/source.
"""
from pathlib import Path
import shutil
import subprocess

from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/wanted-poster/source"
DEST = ROOT / "libs/HighgroundKit/bounty/media"
METRICS = {}


def font(name, width, tracking=0):
    face = instantiateVariableFont(TTFont(SOURCE / "BodoniModa[opsz,wght].ttf"),
                                   {"wght": 800, "opsz": 6}, inplace=True)
    glyphs, outlines = face.getGlyphSet(), {}
    for key in face.getGlyphOrder():
        recording = DecomposingRecordingPen(glyphs)
        glyphs[key].draw(recording)
        pen = TTGlyphPen(None)
        recording.replay(TransformPen(pen, (width, 0, 0, 1, tracking / 2, 0)))
        outlines[key] = pen.glyph()
        advance, left = face["hmtx"].metrics[key]
        face["hmtx"].metrics[key] = (round(advance * width + tracking), round(left * width + tracking / 2))
    face["glyf"].glyphs = outlines
    # Titling metrics: one em is the cap height, with space for accents.
    face["head"].unitsPerEm = 1500
    face["hhea"].ascent, face["hhea"].descent, face["hhea"].lineGap = 1680, -120, 0
    face["OS/2"].sTypoAscender, face["OS/2"].sTypoDescender, face["OS/2"].sTypoLineGap = 1680, -120, 0
    face["OS/2"].fsSelection |= 128
    # Capitals are a font treatment; the player's actual name remains unchanged
    # in the UI data, tooltips, matching, chat links and accessibility text.
    for table in face["cmap"].tables:
        if table.isUnicode():
            for code in list(table.cmap):
                upper = chr(code).upper()
                if len(upper) == 1 and ord(upper) in table.cmap:
                    table.cmap[code] = table.cmap[ord(upper)]
    for tag in ("GPOS", "GSUB", "GDEF", "kern", "DSIG"):
        if tag in face:
            del face[tag]
    for entry in face["name"].names:
        value = {1: name, 2: "Regular", 3: name + " 1.0", 4: name, 6: name,
                 16: name, 17: "Regular"}.get(entry.nameID)
        if value is not None:
            entry.string = value.encode(entry.getEncoding())
    face.save(DEST / (name + ".ttf"))
    cmap = face.getBestCmap()
    METRICS[name] = [round(face["hmtx"].metrics[cmap.get(code, ".notdef")][0] / 1500, 5) for code in range(32, 127)]


def main():
    DEST.mkdir(parents=True, exist_ok=True)
    font("WantedDisplay", 0.72)
    font("WantedName", 0.50)
    font("WantedCaption", 0.55, 600)
    lines = ["-- Generated by tools/build_wanted_assets.py; ASCII advances in ems.", "return {"]
    for name, widths in METRICS.items():
        lines.append("  " + name + " = {")
        for at in range(0, len(widths), 12):
            lines.append("    " + ", ".join(map(str, widths[at:at + 12])) + ",")
        lines.append("  },")
    (ROOT / "tools/wowsim/poster_fonts.lua").write_text("\n".join(lines + ["}", ""]))
    shutil.copyfile(SOURCE / "OFL.txt", DEST / "OFL-wanted.txt")
    subprocess.run(["magick", str(SOURCE / "paper.png"), "-resize", "512x1024!",
                    "-alpha", "off", "-type", "TrueColor", "-compress", "None", str(DEST / "WantedPaper.tga")], check=True)
    subprocess.run(["magick", "-background", "none", str(SOURCE / "scroll.svg"), "-resize", "32x256!",
                    "-type", "TrueColorAlpha", "-compress", "None", str(DEST / "WantedScroll.tga")], check=True)


if __name__ == "__main__":
    main()
